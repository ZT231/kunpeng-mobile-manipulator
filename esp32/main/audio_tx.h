#ifndef AUDIO_TX_H
#define AUDIO_TX_H

#include "esp_err.h"

/* ============================================================
 * audio_tx —— ESP32 → 鲲鹏的 PCM 音频上行（TCP 9001）
 *
 * 【概念（大白话）】麦克风每秒吐 16000 个采样，光在串口打印没用；
 *   这里把它每 256 个采样打包成 512 字节，走一条专门的长连接
 *   持续发给鲲鹏，鲲鹏落成 WAV 就能回放听到人声。
 * 【为什么单独 9001 端口】9000 走的是文本帧 "$...*CK" 短事务；
 *   二进制 PCM 混进去会破坏 CK 解析。音频流是「长时间单方向灌数据」，
 *   和「发一句等一句」的语义完全不同，所以另开一条通道。
 *
 * 🔴 诚实边界：本模块只负责「把采到的 PCM 原样送出去」，
 *   不做 VAD、不做唤醒、不做降噪；这些在鲲鹏侧或后续版本再加。
 * ============================================================ */

/* 鲲鹏音频接收端 audio_sink.py 监听的地址（唯一网段 192.168.77.0/24）。 */
#define AUDIO_TX_HOST   "192.168.77.100"
#define AUDIO_TX_PORT   9001

/* 每次发送的采样数：与 i2s_mic_read 单次读取对齐（256 采样 = 512 字节）。
 * 16kHz 下 256 个采样正好 16ms，凑成流畅的连续流。 */
#define AUDIO_TX_SAMPLES_PER_SEND   256

/* 启动音频上行任务。成功返回 ESP_OK；失败返回 ESP_FAIL。
 * 【为什么拆成任务】app_main 是主任务，若在里面塞一个无限循环读麦，
 *   后续再接别的逻辑会越来越挤；独立任务还能单独压栈深、单独挂核心。 */
esp_err_t audio_tx_start(void);

#endif /* AUDIO_TX_H */
